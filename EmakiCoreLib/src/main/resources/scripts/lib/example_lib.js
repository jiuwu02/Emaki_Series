// ----------------------------------------------------------------------------
// lib/ 目录下的文件会在所有其他脚本之前求值，适合放置被多个脚本复用的工具函数。
// 本文件定义的 `exampleLib` 是一个全局对象，后续脚本可以直接引用。
// ============================================================================

var exampleLib = {

    // 演示曲线：把一个数值映射为另一个数值，供动作段与表达式函数复用。
    curve: function (value) {
        var level = Number(value) || 0;
        return Math.floor(level * 2 + Math.min(level, 10));
    },

    // 演示文本工具：把名称包上一层装饰。
    greet: function (name) {
        return '「脚本示例」' + (name || 'Emaki');
    }
};
